// わるあがき(public/master-data/detail/moves.json 中で type: null の唯一の技)向けの特例。
// TYPE_MODIFIER[""] は防御側18タイプすべてに対して1.0(常に等倍)
// (出典: vendor/jpoke/src/jpoke/data/type_chart.py:2-22)。
const TYPELESS_ROW: Record<string, number> = Object.fromEntries(
  Object.keys(TYPE_CHART).map((defType) => [defType, 1]),
);

export type TypeEffectivenessCategory = 'super' | 'not-very' | 'no-effect';

export interface TypeEffectivenessGroup {
  category: TypeEffectivenessCategory;
  label: string;
  multiplierLabel: string;
  types: string[];
}

// 攻撃技のタイプ(和名。わるあがき等タイプなしの技は null)から、防御側の各タイプに対する倍率を
// 「効果ばつぐん(×2)/いまひとつ(×0.5)/効果がない(×0)」に分類して返す。
// 等倍(×1)のタイプは意図的に含めない(round-09.md B-2「等倍のタイプは列挙しないこと」。
// 18タイプ中、等倍が最多を占めるため列挙すると情報量が薄くなる)。
export function getTypeEffectiveness(attackType: string | null): TypeEffectivenessGroup[] {
  const row = attackType == null ? TYPELESS_ROW : TYPE_CHART[attackType];
  if (!row) return [];

  const superTypes: string[] = [];
  const notVeryTypes: string[] = [];
  const noEffectTypes: string[] = [];
  for (const defType of Object.keys(TYPE_CHART)) {
    const multiplier = row[defType];
    if (multiplier === 2) superTypes.push(defType);
    else if (multiplier === 0.5) notVeryTypes.push(defType);
    else if (multiplier === 0) noEffectTypes.push(defType);
  }

  const groups: TypeEffectivenessGroup[] = [];
  if (superTypes.length > 0) {
    groups.push({ category: 'super', label: '効果ばつぐん', multiplierLabel: '×2', types: superTypes });
  }
  if (notVeryTypes.length > 0) {
    groups.push({ category: 'not-very', label: 'いまひとつ', multiplierLabel: '×0.5', types: notVeryTypes });
  }
  if (noEffectTypes.length > 0) {
    groups.push({ category: 'no-effect', label: '効果がない', multiplierLabel: '×0', types: noEffectTypes });
  }
  return groups;
}
